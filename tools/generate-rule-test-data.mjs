import {readFile, writeFile} from "node:fs/promises";
import {CREATURE_ABILITY_REFERENCES} from "../modules/creature-ability-data.mjs";

const powers = JSON.parse(await readFile(new URL("../game doc/fr/trudvang-powers-fr.json", import.meta.url), "utf8"));
const feats = JSON.parse(await readFile(new URL("../game doc/fr/trudvang-feats-fr.json", import.meta.url), "utf8"));
const abilityIdByName = new Map(Object.entries(CREATURE_ABILITY_REFERENCES).map(([name, reference]) => [name, reference.id]));
const result = {};

function testsFor(entry) {
  return [
    ...(entry.resist ?? []).map((test, index) => ({...test, kind: "resist", index})),
    ...(entry.skillTest ?? []).map((test, index) => ({...test, kind: "skill", index}))
  ];
}

for (const entry of powers) {
  if (!entry.catalogId) continue;
  const tests = testsFor(entry);
  if (tests.length) result[entry.catalogId] = tests;
}

let unmatchedFeats = [];
for (const entry of feats) {
  const tests = testsFor(entry);
  if (!tests.length) continue;
  const abilityId = abilityIdByName.get(entry.name)
    ?? (entry.variants ?? []).map(name => abilityIdByName.get(name)).find(Boolean);
  if (!abilityId) {
    unmatchedFeats.push(entry.name);
    continue;
  }
  result[abilityId] = tests;
}

const body = `// Generated by tools/generate-rule-test-data.mjs from the private French rule-test catalogues.\n// Keep only structured test data here; source descriptions remain in their established content stores.\nexport const RULE_TESTS_BY_CATALOG_ID = ${JSON.stringify(result, null, 2)};\n`;
await writeFile(new URL("../modules/rule-test-data.mjs", import.meta.url), body, "utf8");
console.info(`Generated ${Object.keys(result).length} entries (${Object.values(result).reduce((sum, tests) => sum + tests.length, 0)} tests).`);
if (unmatchedFeats.length) console.warn(`Unmatched creature abilities: ${unmatchedFeats.join(", ")}`);
