// Only abilities already shipped with the starter creatures are included.
import {readFileSync, writeFileSync} from "node:fs";
import {CREATURE_FEAT_SUMMARIES} from "../modules/creature-feats.mjs";
import {deterministicId} from "../modules/skill-pack-data.mjs";
const check = process.argv.includes("--check");

const sources = Object.fromEntries(["fr", "en"].map(code => [code,
  JSON.parse(readFileSync(`game doc/${code}/trudvang-feats-${code}.json`, "utf8"))]));
if (sources.fr.length !== sources.en.length) throw new Error("The bilingual ability sources must be aligned.");
const references = {};
const languages = Object.fromEntries(["fr", "en"].map(code => [code, JSON.parse(readFileSync(`lang/${code}.json`, "utf8"))]));
for (const language of Object.values(languages)) language.TRUDVANG.Content.CreatureAbility = {};
for (const name of Object.keys(CREATURE_FEAT_SUMMARIES)) {
  let index = sources.fr.findIndex(entry => entry.name === name);
  if (index < 0) index = sources.fr.findIndex(entry => entry.variants?.includes(name));
  if (index < 0) throw new Error(`Missing reference ability: ${name}`);
  const id = deterministicId(`creature-ability:${sources.fr[index].name}`);
  const pages = {};
  for (const code of ["fr", "en"]) {
    const entry = sources[code][index];
    if (!entry.summary || !entry.source?.book || !Number.isInteger(entry.source.page)) throw new Error(`Incomplete ability reference: ${name} (${code})`);
    pages[code] = entry.source.page;
    languages[code].TRUDVANG.Content.CreatureAbility[id] = {Summary: entry.summary, SourceBook: entry.source.book};
  }
  references[name] = {id, pages};
}
const moduleText = `// Generated by tools/generate-creature-ability-data.mjs; display text lives in lang/*.json.\nexport const CREATURE_ABILITY_REFERENCES = ${JSON.stringify(references, null, 2)};\n`;
if (check) {
  if (readFileSync("modules/creature-ability-data.mjs", "utf8") !== moduleText) throw new Error("Creature ability references need regeneration.");
  for (const [code, language] of Object.entries(languages)) {
    const current = JSON.parse(readFileSync(`lang/${code}.json`, "utf8")).TRUDVANG.Content.CreatureAbility;
    if (JSON.stringify(current) !== JSON.stringify(language.TRUDVANG.Content.CreatureAbility)) throw new Error(`Creature ability text needs regeneration (${code}).`);
  }
} else {
  writeFileSync("modules/creature-ability-data.mjs", moduleText);
  for (const [code, language] of Object.entries(languages)) writeFileSync(`lang/${code}.json`, JSON.stringify(language, null, 2) + "\n");
}
console.log(`${check ? "Verified" : "Generated"} references for ${Object.keys(references).length} starter creature abilities.`);
